uint32_t muhtari__palette_rgb(uint8_t index)
{
    return palette_warm_ntsc[index];
}

uint16_t muhtari__palette_rgb565(uint8_t index)
{
    return muhtari__palette_rgb565_region(index, MUHTARI_REGION_NTSC);
}

uint32_t muhtari__palette_rgb_region(uint8_t index, uint32_t region)
{
    return region == MUHTARI_REGION_PAL ? palette_warm_pal[index] : palette_warm_ntsc[index];
}

uint16_t muhtari__palette_rgb565_region(uint8_t index, uint32_t region)
{
    uint32_t rgb = muhtari__palette_rgb_region(index, region);
    uint32_t r = (rgb >> 16) & 0xFFu;
    uint32_t g = (rgb >> 8) & 0xFFu;
    uint32_t b = rgb & 0xFFu;
    return (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
}
